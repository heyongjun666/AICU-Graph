"""
executables/handoff_prompts.py — 新会话交接的提示词文案

数据与路径在 ``runtime/handoff.py``；这里只负责两段文案：
  - ``render_checkpoint``：新会话开场的检查点（原任务 + 上一版产出位置 + 上一轮笔记）；
  - ``render_notes_instructions``：要求 Agent 在收尾前写下一轮要用的工作笔记。
"""

_NOTES_SECTIONS = (
    "1. **已确认的结论**：已经查证、之后不用再核实的事实；每条标 `[已验证]` 或 `[推测]`，"
    "并写明依据位置（文件 + 函数/行号，或命令及其输出）；",
    "2. **已做的决定和理由**：选了什么、为什么这样选、考虑过但没采用的方案；",
    "3. **已试过但不行的做法**：做法 + 失败原因，各一行，免得下一轮再踩；",
    "4. **未决问题**：还没弄清、或需要别人/后续轮次处理的事；",
    "5. **必须遵守的约束**：接口约定、不能动的边界、别人明确提出的要求；",
    "6. **最近一次验证**：跑过什么命令、结果如何（含没跑通的）。",
)


def render_notes_instructions(path: str) -> str:
    """工作笔记写入指令块：追加在 Worker 首轮 / 续接 prompt 的事件发布块旁。"""
    lines = [
        "## 📝 工作笔记（交接用）",
        "",
        "你之后可能被唤醒去处理反馈，而**那一轮是一个全新的对话**，不会带着这次的对话历史。"
        "所以收尾前，把接手所需的要点写到下面这个文件：",
        "",
        f"`{path}`",
        "",
        "固定六节，写事实、不写过程：",
        "",
        *_NOTES_SECTIONS,
        "",
        "**增量更新，不要整篇重写**：文件已存在时先读它，只修改这一轮变了的条目、补充新增的，"
        "其余原样保留；被推翻的结论直接改掉或删除，不要新旧并存。",
        "",
        "产出了哪些文件不用写（交付物本身就在工作区）；这个文件**不是交付物**，不要放进产物目录。",
        "",
    ]
    return "\n".join(lines)


def render_checkpoint(pending: dict, notes: str = "") -> str:
    """新会话的检查点：这是一次全新对话，上一轮做了什么要显式交代。

    只给指针不给内容：原任务全文 + 上一版产物位置 + 上一轮笔记。上一版产出本身
    在工作区里，由 Agent 自己按需读取 —— 不把它预先塞进 prompt。
    """
    lines = [
        "## 🔁 新会话检查点",
        "",
        "> 你是在**新会话**中接手这个节点：之前的对话历史不会带入，但你的工作区和上一版产出都还在。",
        "> 下方「你的任务」是**本次请求**，在上一版产出的基础上处理，不要从零重做。",
        "",
    ]
    original = (pending.get('original_task') or '').strip()
    if original:
        lines.extend(["### 上一轮的任务（原任务）", "", original, ""])
    artifacts = [a for a in (pending.get('prior_artifacts') or []) if a]
    if artifacts:
        lines.append("### 上一版产出位置（相对你的工作区）")
        lines.append("")
        lines.extend(f"- {a}" for a in artifacts)
        lines.append("")
    if notes:
        lines.extend([
            "### 上一轮工作笔记",
            "",
            "> 这是你上一轮留给自己的笔记，可能不完整；与工作区里的实际情况不符时，**以实际情况为准**。",
            "> 标 `[已验证]` 的可直接采用；标 `[推测]` 的先核实再用；「已做的决定」没有新证据不要推翻，"
            "「已试过但不行」的做法不要重走。",
            "",
            notes,
            "",
        ])
    lines.extend([
        "### 开工前",
        "",
        "1. 先查看你工作区里上一版产出的目录清单，了解它由哪些文件组成；",
        "2. 只读取与本次请求相关的部分，理解已有的结构、接口和约定后在原有文件上就地处理；",
        "3. 与本次请求无关的既有内容保持原样，不要重写或删除；",
        "4. 收尾前按「工作笔记」的要求**更新**笔记文件（只改变化的部分）。",
        "",
    ])
    return "\n".join(lines)
