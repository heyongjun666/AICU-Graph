"""
executables/default_stub.py — 默认 Stub AICU 实例

当 Manager/Worker 运行在 mode="stub" 且未注入 stub_instance 时，
Registry 会自动使用此默认 stub，让 demo 能跑通完整流程：
  - Manager.expand: 返回一个包含单个 worker step 的 ExecutionPlan
  - Manager.review: 返回 audit_passed=True
  - Worker: 返回 final_output_path 指向的空产物文件
"""

import json
import os
import tempfile


class DefaultStubAICU:
    """默认 stub AICU，实现 ask() 方法。

    根据调用方（Manager/Worker）传入的 prompt 内容判断返回结构：
    - 如果 prompt 以 "## Review Task" 开头（Manager review 阶段，见
      Manager._build_review_prompt 的头部），返回评审通过结果
    - 否则视为 Manager expand 阶段，返回 ExecutionPlan JSON
    """

    def __init__(self):
        self._call_count = 0

    def ask(self, question: str, max_rounds: int = 3) -> dict:
        self._call_count += 1

        # Manager review 阶段：prompt 由 _build_review_prompt 构造，以 "## Review Task" 开头
        if question.startswith("## Review Task"):
            return {
                "overall_passed": True,
                "summary": "Default stub review: all artifacts accepted.",
                "audit_passed": True,
                "defects": [],
            }

        # Manager expand 阶段：返回一个 ExecutionPlan（含单个 worker step）
        plan = {
            "steps": [
                {
                    "step_id": "step_1",
                    "exec_type": "worker",
                    "role": "dev_member",
                    "task": question[:200] if question else "Default stub task",
                    "task_summary": "执行默认 stub 任务",
                    "config": {},
                    "depends_on": [],
                }
            ]
        }

        # Worker 阶段：Worker.run() 会调用 aicu.ask(ctx.node.task)
        # Worker 的 task 是 step.task，不会以 "Review task:" 开头，
        # 但 Worker 期望返回 {"final_output_path": ...} 而不是 plan。
        # 区分方法：Worker 的调用是在 expand 之后，此时 question 是 step.task。
        # 简化处理：如果 question 看起来像是一个 step task（短文本，不是原始用户 task），
        # 返回 worker 结果。但由于 expand 和 worker 的 ask() 调用都用同一个 stub，
        # 我们需要更可靠的区分方式。
        #
        # 最可靠方案：Worker 的 ask() 调用发生在 Manager expand 之后。
        # 但 stub 是无状态的，无法区分。因此改为：始终返回 plan 结构，
        # Worker 侧通过检查返回值是否有 final_output_path 来判断。
        #
        # 更好的方案：Worker 的 task 文本通常较短且是具体任务描述，
        # 而 Manager expand 的 prompt 就是原始用户 task。
        # 但两者格式无法可靠区分。
        #
        # 最终方案：返回一个同时兼容两者的结构。
        # Worker.run() 只读取 result.get("final_output_path")，
        # Manager._parse_plan() 读取 result.get("execution_plan_json")。
        # 所以可以同时包含两个字段，各自取所需。

        # 写一个空的 artifact 文件供 Worker 使用
        artifact_dir = os.path.join(tempfile.gettempdir(), "stub_artifacts")
        os.makedirs(artifact_dir, exist_ok=True)
        artifact_path = os.path.join(artifact_dir, f"output_{self._call_count}.md")
        with open(artifact_path, "w", encoding="utf-8") as f:
            f.write(f"# Stub Output\n\nTask: {question[:500]}\n\nGenerated by DefaultStubAICU.\n")

        return {
            "execution_plan_json": json.dumps(plan, ensure_ascii=False),
            "final_output_path": artifact_path,
            "audit_passed": True,
            "summary": "Default stub execution completed.",
            "scores": {0: 8.0},
            "avg_scores": {0: 8.0},
            "best_id": 0,
            "consensus_reached": True,
            "vote_rounds": 1,
            "audit_defects": [],
            "strategy": "stub",
            "role_config": {},
        }
